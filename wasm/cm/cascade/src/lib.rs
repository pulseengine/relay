/// falcon-core's `Vec3` alias is private, so it is restated here. Same shape
/// (`[f32; 3]`, NED); if that ever diverges this stops compiling, which is the
/// right failure.
type Vec3 = [f32; 3];

struct SingleThreaded<T>(RefCell<T>);
// SAFETY: the component model guarantees single-threaded, non-reentrant access.
unsafe impl<T> Sync for SingleThreaded<T> {}

/// THE SUPERVISOR AND EVERYTHING IT IS BUILT FROM — falcon-core's
/// `SupervisorHost`, which owns the lazily built `FlightSupervisor` plus the
/// stored vehicle tuning, supervisor configuration and calibration.
///
/// SUPERVISOR-P01 clause 1: a `FlightSupervisor`, not a bare `FlightCore`, so
/// the mode machine, the failsafe arbiter and every pre-arm row (all
/// `relay_preflight::CHECK_COUNT` of them) execute INSIDE the published
/// artifact. Before that the shipped component was, in
/// #414's words, "a stabiliser with no supervisor".
///
/// THIS FILE NO LONGER IMPLEMENTS THE SEAM'S RULES (#609, single-source
/// refactor). Which configuration is usable, when a configure may rebuild the
/// supervisor, which rows a fresh supervisor declares failing, and how a
/// calibration survives a rebuild are `falcon_core::host`, unit-tested there
/// once. #611 had them here AND in the native mirror; the split orchestrator
/// (#575) had a third copy. What remains here is the ABI: WIT records copied
/// field-for-field into falcon-core's, and the published state.
///
/// STILL CONSTRUCTED INTO THE SLOT, never by value: this component links an
/// 8 KiB shadow stack and the by-value form of `FlightCore::new` already
/// trapped as an out-of-bounds access. The supervisor is larger (3208 B
/// against the core's 2688 B), and `SupervisorHost` builds it in place.
/// `crates/falcon-core/tests/shadow_stack_budget.rs` holds that number against
/// half the stack so it cannot drift quietly.
static HOST: SingleThreaded<SupervisorHost> = SingleThreaded(RefCell::new(SupervisorHost::new()));

/// THE PUBLISHED STATE, and a monotonic tick that never resets
/// (SWREQ-FALCON-TRANSPORT-P01). Written at the END of every `step`, read by
/// `observer.read-state` WITHOUT running a tick — the integrator's constraint
/// (jess#167): on the M4, observing must not execute the controller.
///
/// The tick is stored once and copied into BOTH `tick-head` and `tick-tail` on
/// read, so an in-process reader always sees a coherent pair. That is not
/// theatre for the cross-core case it exists for: when this state is placed in
/// shared OCRAM, the writer bumps head, writes the body, then bumps tail, and a
/// reader on the other core retries while they disagree. Publishing the same
/// value in both fields here keeps the CONTRACT honest for a single address
/// space while the layout is already correct for the split one.
static PUBLISHED: SingleThreaded<Option<PublishedState>> = SingleThreaded(RefCell::new(None));

/// What `step` latches for observers. Plain copy type — no allocation, no lock.
#[derive(Clone, Copy)]
struct PublishedState {
    tick: u32,
    q: [f32; 4],
    p: [f32; 3],
    v: [f32; 3],
    w: [f32; 3],
    bg: [f32; 3],
    innovation: f32,
    failed_rotor: u8,
    /// `relay_fsm::Mode` as its discriminant (SUPERVISOR-P01 clause 2/3).
    mode: u8,
    /// `FlightSupervisor::failsafe_flags()` verbatim — the CAUSE behind `mode`.
    failsafe: u32,
    valid: u32,
    /// @0.13.0 (TRANSPORT-P02): `FlightSupervisor::prearm_failing_mask()`
    /// verbatim — WHICH pre-arm rows fail, read off the table `command(arm)`
    /// is gated on.
    prearm_failing: u32,
}

/// `valid` bits. A CLEAR bit means NOT MEASURED — never "the value is zero".
/// Absence and zero arriving indistinguishably is the defect class this whole
/// release line keeps finding, so the seam refuses to conflate them.
const V_ATT: u32 = 1 << 0;
const V_POS: u32 = 1 << 1;
const V_VEL: u32 = 1 << 2;
const V_RATE: u32 = 1 << 3;
const V_BIAS: u32 = 1 << 4;
// Bit 5 stays CLEAR: the core does not compute an innovation yet, so the
// published 0.0 is "not measured", not "perfectly consistent" (#638
// finding 11). Set it when a real innovation is published.
#[allow(dead_code)]
const V_INNOV: u32 = 1 << 5;
const V_ROTOR: u32 = 1 << 6;
/// SUPERVISOR-P01. Both are produced every tick once the supervisor runs, so
/// both are set whenever a tick has happened — and BOTH ARE CLEAR before the
/// first tick, where `mode` would otherwise read 0 = `disarmed`. A pre-tick
/// `disarmed` is indistinguishable from a measured one, and clause 3 exists
/// precisely because confusing mode values is how a terminated vehicle gets
/// reported as safe. "Not measured" must not look like "on the ground".
const V_MODE: u32 = 1 << 7;
const V_FAILSAFE: u32 = 1 << 8;
/// @0.13.0 (TRANSPORT-P02): `prearm-failing` is measured. CLEAR before the
/// first tick, where the mask reads 0 — which would otherwise look like
/// "the table would allow an arm".
const V_PREARM: u32 = 1 << 9;

/// `vehicle-config` as falcon-core's record — field for field, no
/// interpretation. NOT validated here and never clamped: each field's domain
/// is `falcon_core::host::VehicleConfig::tuning`, and an out-of-domain record
/// is refused there.
fn vehicle_config(c: &VehicleConfig) -> host::VehicleConfig {
    host::VehicleConfig {
        hover_thrust: c.hover_thrust,
        loop_rate_hz: c.loop_rate_hz,
        pos_var: c.pos_var,
        process_floor_vel: c.process_floor_vel,
        process_floor_pos: c.process_floor_pos,
        altitude_kp: c.altitude_kp,
        altitude_kd: c.altitude_kd,
        altitude_ki: c.altitude_ki,
        position_ki: c.position_ki,
    }
}

/// `supervisor-config` as falcon-core's record — field for field. Validity is
/// `falcon_core::host::SupervisorConfig::is_valid`.
fn supervisor_config(c: &SupervisorConfig) -> host::SupervisorConfig {
    host::SupervisorConfig {
        home: [c.home.x, c.home.y, c.home.z],
        fence_radius: c.fence_radius,
        cruise_alt: c.cruise_alt,
        low_batt_v: c.low_batt_v,
    }
}

/// `sensor-calibration` as falcon-core's `CalParams` — a field-for-field copy,
/// no conversion of units or meaning (`mag-offdiag` keeps its `[xy, xz, yz]`
/// order). NOT validated here and never clamped: `CalParams::is_valid` (finite,
/// accel scale > 0, soft-iron positive definite) is the one rule, applied
/// through `falcon_core::host::validate_calibration`.
fn cal_params(c: &SensorCalibration) -> falcon_core::relay_calib::CalParams {
    let v = |a: &Vec3Wit| [a.x, a.y, a.z];
    falcon_core::relay_calib::CalParams {
        gyro_bias: v(&c.gyro_bias),
        accel_bias: v(&c.accel_bias),
        accel_scale: v(&c.accel_scale),
        mag_offset: v(&c.mag_offset),
        mag_scale: v(&c.mag_scale),
        mag_offdiag: v(&c.mag_offdiag),
    }
}

struct Component;

impl Guest for Component {
    fn step(sensors: SensorFrame, target: Waypoint) -> MotorPwm {
        // Arena reclamation (#574): see falcon_cm_rt::CallScope. First statement,
        // bound to a name so it lives until the body returns.
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        // The host's ACTUAL period. Clamped to [0.1 ms, 100 ms] so a garbage
        // frame cannot wind the filters; a non-finite value falls back to the
        // v0.7 constant, the only rate that was ever safe to assume.
        let dt = if sensors.dt_s.is_finite() {
            sensors.dt_s.clamp(0.0001, 0.1)
        } else {
            0.001
        };

        let imu = sensors.imu;
        // The same frame backend cascade-split uses (falcon-core's
        // `split::FrameBackend`), so a new sensor field cannot reach one
        // adapter and not the other (#638).
        let mut backend = FrameBackend::new(SeamFrame {
            imu: CoreImu {
                accel: [imu.ax, imu.ay, imu.az],
                gyro: [imu.gx, imu.gy, imu.gz],
            },
            dt,
            position: sensors.position_ned.map(|p| [p.x, p.y, p.z]),
            mag: sensors.mag_body.map(|m| [m.x, m.y, m.z]),
            heading: sensors.heading_rad,
            motor_rpm: sensors.motor_rpm.map(|r| [r.m1, r.m2, r.m3, r.m4]),
            battery_v: sensors.battery_v,
        });

        {
            let mut host = HOST.0.borrow_mut();
            // `target` IS THE MISSION-MODE SETPOINT, NOT A POSITION COMMAND —
            // the semantic change at @0.12.0 a host must be told about. The
            // supervisor OWNS the position setpoint: it derives one per mode
            // (Takeoff/Loiter hold a horizontal point latched on entry, RTL
            // flies home at `cruise-alt`, Land descends, Mission FOLLOWS the
            // target). OUTSIDE MISSION THE TARGET IS IGNORED. THAT IS THE POINT
            // of SUPERVISOR-P01: a supervised vehicle sometimes declines to go
            // where it is sent. IN MISSION IT IS A LIVE FOLLOW SETPOINT (#609
            // finding 4): reaching it ends nothing, a non-finite one is
            // rejected, and no fresh one for 1.0 s takes the stale-target HOLD
            // (failsafe bit 8). `SupervisorHost::step` builds the supervisor if
            // absent, delivers the sample and ticks; the rule lives there.
            let sup = host.step([target.north, target.east, target.down], &mut backend);

            // LATCH FOR OBSERVERS, after the tick so the state corresponds to
            // the motors this call returns.
            let ns = sup.state();
            let failed = sup.core().failed_motor();
            // SUPERVISOR-P01 clause 2. `mode` is the OUTCOME, `failsafe` the
            // CAUSE; publishing only the first would show a consumer the vehicle
            // diverting with no way to tell a flat pack from a geofence breach.
            // Bit 7 (`arm-blocked`) is the same table `command` gates on; no
            // re-declaration is needed since a step no longer overwrites
            // `FailsafeConfigured` (#609 single-source refactor).
            let mode = sup.mode() as u8;
            let failsafe = sup.failsafe_flags();
            let prearm_failing = sup.prearm_failing_mask();
            let mut prev = PUBLISHED.0.borrow_mut();
            let tick = prev.as_ref().map(|s| s.tick.wrapping_add(1)).unwrap_or(0);
            // Every field below is produced by the core each tick, so all are
            // valid; `failed-rotor` is valid as a READING (0xFF = no fault),
            // which is distinct from "not measured".
            let valid = V_ATT
                | V_POS
                | V_VEL
                | V_RATE
                | V_BIAS
                | V_ROTOR
                | V_MODE
                | V_FAILSAFE
                | V_PREARM;
            *prev = Some(PublishedState {
                tick,
                q: ns.q,
                p: ns.p,
                v: ns.v,
                w: [imu.gx, imu.gy, imu.gz],
                bg: ns.b_g,
                innovation: 0.0,
                failed_rotor: failed.map(|i| i as u8).unwrap_or(0xFF),
                mode,
                failsafe,
                valid,
                prearm_failing,
            });
        }

        MotorPwm {
            m1: backend.motors[0],
            m2: backend.motors[1],
            m3: backend.motors[2],
            m4: backend.motors[3],
        }
    }

    /// Install the vehicle configuration and rebuild the supervisor from it —
    /// ONLY while a rebuild loses nothing; otherwise the call is REJECTED and
    /// `cfg` discarded (#609 finding 1). An out-of-domain configuration is
    /// refused (never clamped) and the previous valid one stays in force; with
    /// none ever valid, arming is refused. The rules are
    /// `SupervisorHost::configure_vehicle` / `rebuild_permitted` /
    /// `VehicleConfig::tuning`. The WIT return type is unit, so a refusal is
    /// silent here; a host re-reads `observer.read-state`.
    fn configure(cfg: VehicleConfig) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        HOST.0.borrow_mut().configure_vehicle(vehicle_config(&cfg));
    }
}

/// THE RETURN DIRECTION (SWREQ-FALCON-TRANSPORT-P01).
///
/// Reads the state `step` latched, WITHOUT running a control tick. Before this
/// existed the seam was `step(sensors, target) -> motor-pwm` and nothing else,
/// so the verified MAVLink telemetry stack (MAVLINK-P06, v1.119) had nothing to
/// read, no log could be written, and a shadow flight against a reference
/// filter produced no comparable evidence. Christof put it as "the cascade is
/// only a middle"; this is one half of the answer.
impl ObserverGuest for Component {
    fn read_state() -> FlightState {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();
        let s = PUBLISHED.0.borrow();
        match s.as_ref() {
            Some(p) => FlightState {
                // Same value in head and tail: an in-process reader cannot
                // observe a tear. The FIELDS are ordered for the cross-core
                // case (head first, tail last) so the layout is already right
                // when this lands in shared OCRAM.
                tick_head: p.tick,
                qw: p.q[0],
                qx: p.q[1],
                qy: p.q[2],
                qz: p.q[3],
                pos_n: p.p[0],
                pos_e: p.p[1],
                pos_d: p.p[2],
                vel_n: p.v[0],
                vel_e: p.v[1],
                vel_d: p.v[2],
                wx: p.w[0],
                wy: p.w[1],
                wz: p.w[2],
                bgx: p.bg[0],
                bgy: p.bg[1],
                bgz: p.bg[2],
                innovation: p.innovation,
                failed_rotor: p.failed_rotor,
                mode: p.mode,
                failsafe: p.failsafe,
                valid: p.valid,
                prearm_failing: p.prearm_failing,
                tick_tail: p.tick,
            },
            // NO TICK HAS RUN. Every field is zero and `valid` is 0, so a
            // reader sees "nothing measured" rather than a plausible-looking
            // level attitude at the origin. Returning zeros WITH the valid bits
            // set would be the absence-looks-like-data defect again.
            None => FlightState {
                tick_head: 0,
                qw: 1.0,
                qx: 0.0,
                qy: 0.0,
                qz: 0.0,
                pos_n: 0.0,
                pos_e: 0.0,
                pos_d: 0.0,
                vel_n: 0.0,
                vel_e: 0.0,
                vel_d: 0.0,
                wx: 0.0,
                wy: 0.0,
                wz: 0.0,
                bgx: 0.0,
                bgy: 0.0,
                bgz: 0.0,
                innovation: 0.0,
                failed_rotor: 0xFF,
                // NOT `disarmed`. 0 is a MEANINGFUL mode value, so publishing it
                // with `V_MODE` clear is the whole contract: a reader that
                // ignores `valid` and trusts this byte would read "safely on the
                // ground" out of "no tick has ever run". `failsafe` is 0 for the
                // same reason — no cause has been observed, which is not the
                // same as no cause existing.
                mode: 0,
                failsafe: 0,
                valid: 0,
                // 0 with `V_PREARM` clear: NOT MEASURED, never "would arm".
                prearm_failing: 0,
                tick_tail: 0,
            },
        }
    }
}

/// THE COMMAND DIRECTION (SUPERVISOR-P01 clause 1 + 4).
///
/// Before this the `cascade` world exported `step` and `configure` and nothing
/// else, so the mode machine, the failsafe arbiter and the pre-arm rows were
/// implemented, tested, Kani-proven in places — and UNREACHABLE from the shipped
/// seam. That is ORPHAN-P01's fourth state (implemented, verified, advertised,
/// unreachable) occurring at the seam rather than inside a crate.
impl PilotGuest for Component {
    /// Install the supervisor's safety configuration and rebuild the supervisor
    /// from it — ONLY while a rebuild loses nothing; otherwise REJECTED and
    /// discarded (#609 finding 1). An INVALID configuration is never clamped:
    /// it counts as none and arming is refused by `FailsafeConfigured` (#609
    /// finding 3). The rules are `SupervisorHost::configure_supervisor` and
    /// `SupervisorConfig::is_valid`.
    fn configure_supervisor(cfg: SupervisorConfig) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        HOST.0
            .borrow_mut()
            .configure_supervisor(supervisor_config(&cfg));
    }

    /// Install the IMU / magnetometer calibration (relay#586, #609): in place,
    /// accepted only while `disarmed` (or before the first build), and an
    /// INVALID one revokes any earlier calibration so `arm` is refused. The
    /// rules are `SupervisorHost::configure_calibration` and
    /// `validate_calibration`.
    fn configure_calibration(cal: SensorCalibration) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        HOST.0.borrow_mut().configure_calibration(cal_params(&cal));
    }

    /// Deliver one pilot command to the mode machine.
    ///
    /// The supervisor is built here if it does not exist yet, rather than the
    /// command being dropped: a host whose first act is `arm` must get a real
    /// verdict from the pre-arm table, not silence. That verdict is a REFUSAL
    /// until a `step` has run (`falcon_core::host::ROWS_FED_BY_STEP`, #609
    /// finding 2).
    fn command(cmd: PilotCommand, level: bool, throttle_low: bool) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        use falcon_core::relay_fsm::Event;
        // EXHAUSTIVE on purpose — no `_` arm. The seam's enum is deliberately
        // narrower than `relay_fsm::Event` (it withholds the four physical
        // observations), and if a variant is ever added to either side this
        // match is where it has to be considered rather than silently absorbed.
        let ev = match cmd {
            PilotCommand::Arm => Event::Arm,
            PilotCommand::RequestTakeoff => Event::RequestTakeoff,
            PilotCommand::RequestMission => Event::RequestMission,
            PilotCommand::RequestLoiter => Event::RequestLoiter,
            PilotCommand::RequestRtl => Event::RequestRtl,
            PilotCommand::RequestLand => Event::RequestLand,
            PilotCommand::RequestDisarm => Event::RequestDisarm,
            PilotCommand::Terminate => Event::Terminate,
        };

        HOST.0.borrow_mut().command(ev, level, throttle_low);
    }
}

