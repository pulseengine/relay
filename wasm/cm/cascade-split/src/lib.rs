/// See `cascade`'s `CORE`. Built lazily; dropping it is what `configure` and
/// `configure-supervisor` do, and rebuilding it rebuilds both partitions.
static CORE: SingleThreaded<Option<FlightSupervisor<RemoteCore>>> =
    SingleThreaded(RefCell::new(None));

/// See `cascade`'s `SUPCFG`. `None` is NOT a neutral state.
static SUPCFG: SingleThreaded<Option<SupervisorConfig>> = SingleThreaded(RefCell::new(None));

/// See `cascade`'s `PUBLISHED`. The tick is monotonic and NOT reset by either
/// configure call.
static PUBLISHED: SingleThreaded<Option<PublishedState>> = SingleThreaded(RefCell::new(None));

#[derive(Clone, Copy)]
struct PublishedState {
    tick: u32,
    q: [f32; 4],
    p: [f32; 3],
    v: [f32; 3],
    w: [f32; 3],
    bg: [f32; 3],
    innovation: f32,
    failed_rotor: u8,
    mode: u8,
    failsafe: u32,
    valid: u32,
}

/// `valid` bits. A CLEAR bit means NOT MEASURED — never "the value is zero".
const V_ATT: u32 = 1 << 0;
const V_POS: u32 = 1 << 1;
const V_VEL: u32 = 1 << 2;
const V_RATE: u32 = 1 << 3;
const V_BIAS: u32 = 1 << 4;
const V_INNOV: u32 = 1 << 5;
const V_ROTOR: u32 = 1 << 6;
const V_MODE: u32 = 1 << 7;
const V_FAILSAFE: u32 = 1 << 8;

/// The host's calibration, if it supplied one.
static CONFIG: SingleThreaded<Option<VehicleConfig>> = SingleThreaded(RefCell::new(None));

/// See `cascade`'s `sane`.
fn sane(v: f32, default: f32, positive: bool) -> f32 {
    if v.is_finite() && (!positive || v > 0.0) {
        v
    } else {
        default
    }
}

/// See `cascade`'s `SUP_FENCE_UNSET` — geofence INACTIVE, not 0 m.
const SUP_FENCE_UNSET: f32 = 1.0e9;
/// See `cascade`'s `SUP_LOW_BATT_UNSET` — no guessed cell count.
const SUP_LOW_BATT_UNSET: f32 = 0.0;
/// See `cascade`'s `SUP_CRUISE_UNSET` — metres AGL, POSITIVE.
const SUP_CRUISE_UNSET: f32 = 2.0;

/// See `cascade`'s `supcfg_valid` (#609 finding 3): an invalid configuration is
/// treated exactly like none — never clamped, `FailsafeConfigured` FALSE.
fn supcfg_valid(c: &SupervisorConfig) -> bool {
    let pos = |v: f32| v.is_finite() && v > 0.0;
    c.home.x.is_finite()
        && c.home.y.is_finite()
        && c.home.z.is_finite()
        && pos(c.fence_radius)
        && pos(c.cruise_alt)
        && pos(c.low_batt_v)
}

/// See `cascade`'s `cal_params` (#586): field for field, or `None` if any
/// component is non-finite or any scale is not > 0. Never clamped.
fn cal_params(c: &SensorCalibration) -> Option<CalParams> {
    let pos = |v: f32| v.is_finite() && v > 0.0;
    let finite3 = |v: &WitVec3| v.x.is_finite() && v.y.is_finite() && v.z.is_finite();
    let pos3 = |v: &WitVec3| pos(v.x) && pos(v.y) && pos(v.z);
    let ok = finite3(&c.gyro_bias)
        && finite3(&c.accel_bias)
        && pos3(&c.accel_scale)
        && finite3(&c.mag_offset)
        && pos3(&c.mag_scale);
    let v = |a: &WitVec3| [a.x, a.y, a.z];
    ok.then(|| CalParams {
        gyro_bias: v(&c.gyro_bias),
        accel_bias: v(&c.accel_bias),
        accel_scale: v(&c.accel_scale),
        mag_offset: v(&c.mag_offset),
        mag_scale: v(&c.mag_scale),
    })
}

/// See `cascade`'s `CALIB`: the last VALID calibration the host sent, or the
/// identity. Kept here so a rebuild — which here rebuilds both partitions, and
/// a rebuilt partition starts at the identity — re-sends it. It is NOT what the
/// `CalibrationPresent` row reads: that is the estimator's own value, read back
/// across the seam.
static CALIB: SingleThreaded<CalParams> = SingleThreaded(RefCell::new(CalParams::identity()));

/// See `cascade`'s `usable_supcfg`.
fn usable_supcfg(cfg: Option<&SupervisorConfig>) -> Option<&SupervisorConfig> {
    cfg.filter(|c| supcfg_valid(c))
}

/// See `cascade`'s `sup_params`: a usable configuration VERBATIM, anything else
/// the inactive constants.
fn sup_params(cfg: Option<&SupervisorConfig>) -> ([f32; 3], f32, f32, f32) {
    match usable_supcfg(cfg) {
        None => (
            [0.0, 0.0, 0.0],
            SUP_FENCE_UNSET,
            SUP_CRUISE_UNSET,
            SUP_LOW_BATT_UNSET,
        ),
        Some(c) => (
            [c.home.x, c.home.y, c.home.z],
            c.fence_radius,
            c.cruise_alt,
            c.low_batt_v,
        ),
    }
}

/// See `cascade`'s `ROWS_FED_BY_STEP` (#609 finding 2) — the SAME twelve rows,
/// declared FALSE on every fresh supervisor.
const ROWS_FED_BY_STEP: [falcon_core::relay_preflight::CheckId; 12] = {
    use falcon_core::relay_preflight::CheckId as C;
    [
        C::SensorsHealthy,
        C::EstimatorConverged,
        C::CalibrationPresent,
        C::GeofenceLoaded,
        C::BatteryOk,
        C::FailsafeConfigured,
        C::EstimatorInnovation,
        C::GnssAgreement,
        C::GeofenceSane,
        C::BatteryTakeoffMargin,
        C::MotorsHealthy,
        C::NoFailsafeLatched,
    ]
};

/// See `cascade`'s `ensure_supervisor`, in the same order. The one difference:
/// building the supervisor here ALSO rebuilds both partitions (with their
/// tuning), because in `cascade` building the supervisor builds a fresh
/// `FlightCore` inside it. The calibration is then installed through the
/// supervisor, which forwards it to both rebuilt partitions.
fn ensure_supervisor<'a>(
    slot: &'a mut Option<FlightSupervisor<RemoteCore>>,
    cfg: Option<&VehicleConfig>,
    supcfg: Option<&SupervisorConfig>,
) -> &'a mut FlightSupervisor<RemoteCore> {
    let fresh = slot.is_none();
    let (home, fence, cruise, low_batt) = sup_params(supcfg);
    let sup = slot.get_or_insert_with(|| {
        reset_partitions(cfg);
        FlightSupervisor::with_core(SplitCore(WitSeam), home, fence, cruise, low_batt)
    });
    if fresh {
        sup.set_calibration(*CALIB.0.borrow());
        for id in ROWS_FED_BY_STEP {
            sup.set_check(id, false);
        }
    }
    sup.set_check(
        falcon_core::relay_preflight::CheckId::FailsafeConfigured,
        usable_supcfg(supcfg).is_some(),
    );
    sup
}

/// See `cascade`'s `rebuild_permitted` (#609 finding 1): only with no
/// supervisor, or a Disarmed one holding no isolated rotor, no nav-integrity
/// latch and no latched low/critical battery. The core facts are read through
/// the seam (`SplitCore`), from the partitions that own them.
fn rebuild_permitted(slot: &Option<FlightSupervisor<RemoteCore>>) -> bool {
    match slot {
        None => true,
        Some(sup) => {
            let batt = sup.battery();
            sup.mode() == falcon_core::relay_fsm::Mode::Disarmed
                && sup.core().failed_motor().is_none()
                && !sup.core().nav_compromised()
                && !batt.low
                && !batt.critical
        }
    }
}

struct Component;

impl Guest for Component {
    /// See `cascade`'s `step`.
    fn step(sensors: SensorFrame, target: Waypoint) -> MotorPwm {
        reset_arena();

        let dt = if sensors.dt_s.is_finite() {
            sensors.dt_s.clamp(0.0001, 0.1)
        } else {
            0.001
        };

        let imu = sensors.imu;
        // See `cascade`'s `FrameBackend`: the frame as the backend's answers,
        // the motor command caught on the way out — falcon-core's, so the
        // CI-run test drives the supervisor through the same type.
        let mut backend = FrameBackend::new(SeamFrame {
            imu: CoreImu {
                accel: [imu.ax, imu.ay, imu.az],
                gyro: [imu.gx, imu.gy, imu.gz],
            },
            dt,
            position: sensors.position_ned.map(|p| [p.x, p.y, p.z]),
            mag: sensors.mag_body.map(|m| [m.x, m.y, m.z]),
            heading: sensors.heading_rad,
            motor_rpm: sensors.motor_rpm.map(|r| [r.m1, r.m2, r.m3, r.m4]),
            battery_v: sensors.battery_v,
        });

        {
            let mut guard = CORE.0.borrow_mut();
            let cfg = CONFIG.0.borrow();
            let supcfg = SUPCFG.0.borrow();
            let sup = ensure_supervisor(&mut guard, cfg.as_ref(), supcfg.as_ref());

            // `target` is a MISSION LEG at @0.12.0 — see `cascade`.
            sup.set_mission([target.north, target.east, target.down]);
            sup.step(&mut backend);

            let ns = sup.state();
            let failed = sup.core().failed_motor();
            // RE-DECLARE BEFORE READING — see `cascade`.
            sup.set_check(
                falcon_core::relay_preflight::CheckId::FailsafeConfigured,
                usable_supcfg(supcfg.as_ref()).is_some(),
            );
            let mode = sup.mode() as u8;
            let failsafe = sup.failsafe_flags();
            let mut prev = PUBLISHED.0.borrow_mut();
            let tick = prev.as_ref().map(|s| s.tick.wrapping_add(1)).unwrap_or(0);
            let valid =
                V_ATT | V_POS | V_VEL | V_RATE | V_BIAS | V_INNOV | V_ROTOR | V_MODE | V_FAILSAFE;
            *prev = Some(PublishedState {
                tick,
                q: ns.q,
                p: ns.p,
                v: ns.v,
                w: [imu.gx, imu.gy, imu.gz],
                bg: ns.b_g,
                innovation: 0.0,
                failed_rotor: failed.map(|i| i as u8).unwrap_or(0xFF),
                mode,
                failsafe,
                valid,
            });
        }

        MotorPwm {
            m1: backend.motors[0],
            m2: backend.motors[1],
            m3: backend.motors[2],
            m4: backend.motors[3],
        }
    }

    /// See `cascade`'s `configure`: ONLY while `rebuild_permitted`, store and
    /// drop the supervisor (the next call rebuilds it AND both partitions);
    /// otherwise the call is REJECTED and `cfg` discarded (#609 finding 1).
    fn configure(cfg: VehicleConfig) {
        reset_arena();

        let mut core = CORE.0.borrow_mut();
        if !rebuild_permitted(&core) {
            return;
        }
        *CONFIG.0.borrow_mut() = Some(cfg);
        *core = None;
    }
}

