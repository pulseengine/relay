/// The flight core the supervisor drives: falcon-core's `SplitCore` — the
/// forwarding, including the #452 edge and the estimate-only path — over the
/// WIT imports. The forwarding itself is `falcon_core::split::SplitCore`, which
/// `crates/falcon-core/tests/supervised_core_split.rs` drives in CI with real
/// in-process partitions; this file adds only the WIT encoding ([`WitSeam`]).
type RemoteCore = SplitCore<WitSeam>;

/// The eight seam calls, as WIT imports. Zero-sized: the state lives in
/// `cascade-estimator` and `cascade-control`. Pure encoding, no logic.
struct WitSeam;

fn nav_from_wit(n: WitNav) -> NavState {
    NavState {
        q: [n.qw, n.qx, n.qy, n.qz],
        v: [n.vel_n, n.vel_e, n.vel_d],
        p: [n.pos_n, n.pos_e, n.pos_d],
        b_g: [n.bgx, n.bgy, n.bgz],
        b_a: [n.bax, n.bay, n.baz],
    }
}

fn nav_to_wit(n: &NavState) -> WitNav {
    WitNav {
        qw: n.q[0],
        qx: n.q[1],
        qy: n.q[2],
        qz: n.q[3],
        vel_n: n.v[0],
        vel_e: n.v[1],
        vel_d: n.v[2],
        pos_n: n.p[0],
        pos_e: n.p[1],
        pos_d: n.p[2],
        bgx: n.b_g[0],
        bgy: n.b_g[1],
        bgz: n.b_g[2],
        bax: n.b_a[0],
        bay: n.b_a[1],
        baz: n.b_a[2],
    }
}

fn v3(v: Vec3) -> WitVec3 {
    WitVec3 {
        x: v[0],
        y: v[1],
        z: v[2],
    }
}

fn imu_to_wit(i: CoreImu) -> WitImu {
    WitImu {
        ax: i.accel[0],
        ay: i.accel[1],
        az: i.accel[2],
        gx: i.gyro[0],
        gy: i.gyro[1],
        gz: i.gyro[2],
    }
}

fn frame_to_wit(f: &SeamFrame) -> SensorFrame {
    SensorFrame {
        imu: imu_to_wit(f.imu),
        dt_s: f.dt,
        position_ned: f.position.map(v3),
        mag_body: f.mag.map(v3),
        heading_rad: f.heading,
        motor_rpm: f.motor_rpm.map(|r| RotorRpm {
            m1: r[0],
            m2: r[1],
            m3: r[2],
            m4: r[3],
        }),
        battery_v: f.battery_v,
    }
}

impl PartitionSeam for WitSeam {
    fn estimator_tick(&mut self, f: &SeamFrame, in_flight: Option<bool>) -> NavState {
        nav_from_wit(estimator::tick(frame_to_wit(f), in_flight))
    }
    fn estimator_nav(&self) -> NavState {
        nav_from_wit(estimator::read_nav())
    }
    fn estimator_health(&self) -> EstimatorHealth {
        let h = estimator::read_health();
        EstimatorHealth {
            tilt_uncertainty: h.tilt_uncertainty,
            nav_compromised: h.nav_compromised,
            gnss_diverged: h.gnss_diverged,
        }
    }
    fn control_tick(&mut self, nav: &NavState, f: &SeamFrame) -> [f32; 4] {
        let o = flight_control::tick(nav_to_wit(nav), frame_to_wit(f));
        [o.m1, o.m2, o.m3, o.m4]
    }
    fn control_keep_warm(&mut self, imu: CoreImu) {
        flight_control::keep_warm(imu_to_wit(imu));
    }
    fn control_set_position(&mut self, ned: Vec3) {
        flight_control::set_position(v3(ned));
    }
    fn control_set_landing(&mut self, on: bool) {
        flight_control::set_landing(on);
    }
    fn control_status(&self) -> ControlStatus {
        let s = flight_control::read_status();
        ControlStatus {
            flying: s.flying,
            max_motor: s.max_motor,
            failed_rotor: match s.failed_rotor {
                0xFF => None,
                i => Some(i as usize),
            },
        }
    }
}

/// Rebuild both partitions, each with its share of the calibration — what
/// `FlightSupervisor::new` + `set_hover_thrust` + `apply_tuning` do to the
/// fused core in `cascade`. `None` keeps falcon-core's built-in defaults, as an
/// unconfigured `cascade` does.
///
/// Sanitised HERE, with `cascade`'s rules and fallbacks, so the partitions
/// receive exactly the values the fused core's setters receive there. The
/// hover thrust goes through `CascadePartition::set_hover_thrust_core`, which
/// clamps to [0, 1] like `FlightSupervisor::set_hover_thrust`; the two differ
/// only on a non-finite input, which `sane` has already replaced.
fn reset_partitions(cfg: Option<&VehicleConfig>) {
    estimator::configure(cfg.map(|c| EstimatorConfig {
        pos_var: sane(c.pos_var, 0.01, true),
        process_floor_vel: sane(c.process_floor_vel, 0.0, false),
        process_floor_pos: sane(c.process_floor_pos, 0.0, false),
    }));
    flight_control::configure(cfg.map(|c| ControlConfig {
        hover_thrust: sane(c.hover_thrust, 0.5, true),
        altitude_kp: sane(c.altitude_kp, 0.05, false),
        altitude_kd: sane(c.altitude_kd, 0.30, false),
        altitude_ki: sane(c.altitude_ki, 0.0, false),
        // falcon-core's default ki_pos is 0.02, NOT zero (see `cascade`).
        position_ki: sane(c.position_ki, 0.02, false),
    }));
}

// ── from here on: `cascade`'s seam logic, with `RemoteCore` as the core ─────

/// See `cascade`'s `CORE`. Built lazily; dropping it is what `configure` and
/// `configure-supervisor` do, and rebuilding it rebuilds both partitions.
static CORE: SingleThreaded<Option<FlightSupervisor<RemoteCore>>> =
    SingleThreaded(RefCell::new(None));

/// See `cascade`'s `SUPCFG`. `None` is NOT a neutral state.
static SUPCFG: SingleThreaded<Option<SupervisorConfig>> = SingleThreaded(RefCell::new(None));

/// See `cascade`'s `PUBLISHED`. The tick is monotonic and NOT reset by either
/// configure call.
static PUBLISHED: SingleThreaded<Option<PublishedState>> = SingleThreaded(RefCell::new(None));

#[derive(Clone, Copy)]
struct PublishedState {
    tick: u32,
    q: [f32; 4],
    p: [f32; 3],
    v: [f32; 3],
    w: [f32; 3],
    bg: [f32; 3],
    innovation: f32,
    failed_rotor: u8,
    mode: u8,
    failsafe: u32,
    valid: u32,
}

/// `valid` bits. A CLEAR bit means NOT MEASURED — never "the value is zero".
const V_ATT: u32 = 1 << 0;
const V_POS: u32 = 1 << 1;
const V_VEL: u32 = 1 << 2;
const V_RATE: u32 = 1 << 3;
const V_BIAS: u32 = 1 << 4;
const V_INNOV: u32 = 1 << 5;
const V_ROTOR: u32 = 1 << 6;
const V_MODE: u32 = 1 << 7;
const V_FAILSAFE: u32 = 1 << 8;

/// The host's calibration, if it supplied one.
static CONFIG: SingleThreaded<Option<VehicleConfig>> = SingleThreaded(RefCell::new(None));

/// See `cascade`'s `sane`.
fn sane(v: f32, default: f32, positive: bool) -> f32 {
    if v.is_finite() && (!positive || v > 0.0) {
        v
    } else {
        default
    }
}

/// See `cascade`'s `SUP_FENCE_UNSET` — geofence INACTIVE, not 0 m.
const SUP_FENCE_UNSET: f32 = 1.0e9;
/// See `cascade`'s `SUP_LOW_BATT_UNSET` — no guessed cell count.
const SUP_LOW_BATT_UNSET: f32 = 0.0;
/// See `cascade`'s `SUP_CRUISE_UNSET` — metres AGL, POSITIVE.
const SUP_CRUISE_UNSET: f32 = 2.0;

/// See `cascade`'s `sup_params`.
fn sup_params(cfg: Option<&SupervisorConfig>) -> ([f32; 3], f32, f32, f32) {
    match cfg {
        None => (
            [0.0, 0.0, 0.0],
            SUP_FENCE_UNSET,
            SUP_CRUISE_UNSET,
            SUP_LOW_BATT_UNSET,
        ),
        Some(c) => (
            [
                sane(c.home.x, 0.0, false),
                sane(c.home.y, 0.0, false),
                sane(c.home.z, 0.0, false),
            ],
            sane(c.fence_radius, SUP_FENCE_UNSET, true),
            sane(c.cruise_alt, SUP_CRUISE_UNSET, true),
            sane(c.low_batt_v, SUP_LOW_BATT_UNSET, false),
        ),
    }
}

/// See `cascade`'s `ensure_supervisor`. The one difference: building the
/// supervisor here ALSO rebuilds both partitions, because in `cascade` building
/// the supervisor builds a fresh `FlightCore` inside it.
fn ensure_supervisor<'a>(
    slot: &'a mut Option<FlightSupervisor<RemoteCore>>,
    cfg: Option<&VehicleConfig>,
    supcfg: Option<&SupervisorConfig>,
) -> &'a mut FlightSupervisor<RemoteCore> {
    let (home, fence, cruise, low_batt) = sup_params(supcfg);
    let sup = slot.get_or_insert_with(|| {
        reset_partitions(cfg);
        FlightSupervisor::with_core(SplitCore(WitSeam), home, fence, cruise, low_batt)
    });
    sup.set_check(
        falcon_core::relay_preflight::CheckId::FailsafeConfigured,
        supcfg.is_some(),
    );
    sup
}

struct Component;

impl Guest for Component {
    /// See `cascade`'s `step`.
    fn step(sensors: SensorFrame, target: Waypoint) -> MotorPwm {
        let dt = if sensors.dt_s.is_finite() {
            sensors.dt_s.clamp(0.0001, 0.1)
        } else {
            0.001
        };

        let imu = sensors.imu;
        // See `cascade`'s `FrameBackend`: the frame as the backend's answers,
        // the motor command caught on the way out — falcon-core's, so the
        // CI-run test drives the supervisor through the same type.
        let mut backend = FrameBackend::new(SeamFrame {
            imu: CoreImu {
                accel: [imu.ax, imu.ay, imu.az],
                gyro: [imu.gx, imu.gy, imu.gz],
            },
            dt,
            position: sensors.position_ned.map(|p| [p.x, p.y, p.z]),
            mag: sensors.mag_body.map(|m| [m.x, m.y, m.z]),
            heading: sensors.heading_rad,
            motor_rpm: sensors.motor_rpm.map(|r| [r.m1, r.m2, r.m3, r.m4]),
            battery_v: sensors.battery_v,
        });

        {
            let mut guard = CORE.0.borrow_mut();
            let cfg = CONFIG.0.borrow();
            let supcfg = SUPCFG.0.borrow();
            let sup = ensure_supervisor(&mut guard, cfg.as_ref(), supcfg.as_ref());

            // `target` is a MISSION LEG at @0.12.0 — see `cascade`.
            sup.set_mission([target.north, target.east, target.down]);
            sup.step(&mut backend);

            let ns = sup.state();
            let failed = sup.core().failed_motor();
            // RE-DECLARE BEFORE READING — see `cascade`.
            sup.set_check(
                falcon_core::relay_preflight::CheckId::FailsafeConfigured,
                supcfg.is_some(),
            );
            let mode = sup.mode() as u8;
            let failsafe = sup.failsafe_flags();
            let mut prev = PUBLISHED.0.borrow_mut();
            let tick = prev.as_ref().map(|s| s.tick.wrapping_add(1)).unwrap_or(0);
            let valid =
                V_ATT | V_POS | V_VEL | V_RATE | V_BIAS | V_INNOV | V_ROTOR | V_MODE | V_FAILSAFE;
            *prev = Some(PublishedState {
                tick,
                q: ns.q,
                p: ns.p,
                v: ns.v,
                w: [imu.gx, imu.gy, imu.gz],
                bg: ns.b_g,
                innovation: 0.0,
                failed_rotor: failed.map(|i| i as u8).unwrap_or(0xFF),
                mode,
                failsafe,
                valid,
            });
        }

        MotorPwm {
            m1: backend.motors[0],
            m2: backend.motors[1],
            m3: backend.motors[2],
            m4: backend.motors[3],
        }
    }

    /// See `cascade`'s `configure`: store, and drop the supervisor. The next
    /// call rebuilds it AND both partitions from the new calibration.
    fn configure(cfg: VehicleConfig) {
        *CONFIG.0.borrow_mut() = Some(cfg);
        *CORE.0.borrow_mut() = None;
    }
}

impl ObserverGuest for Component {
    /// See `cascade`'s `read_state`.
    fn read_state() -> FlightState {
        let s = PUBLISHED.0.borrow();
        match s.as_ref() {
            Some(p) => FlightState {
                tick_head: p.tick,
                qw: p.q[0],
                qx: p.q[1],
                qy: p.q[2],
                qz: p.q[3],
                pos_n: p.p[0],
                pos_e: p.p[1],
                pos_d: p.p[2],
                vel_n: p.v[0],
                vel_e: p.v[1],
                vel_d: p.v[2],
                wx: p.w[0],
                wy: p.w[1],
                wz: p.w[2],
                bgx: p.bg[0],
                bgy: p.bg[1],
                bgz: p.bg[2],
                innovation: p.innovation,
                failed_rotor: p.failed_rotor,
                mode: p.mode,
                failsafe: p.failsafe,
                valid: p.valid,
                tick_tail: p.tick,
            },
            // NO TICK HAS RUN: `valid` is 0 and `mode` 0 is NOT `disarmed`.
            None => FlightState {
                tick_head: 0,
                qw: 1.0,
                qx: 0.0,
                qy: 0.0,
                qz: 0.0,
                pos_n: 0.0,
                pos_e: 0.0,
                pos_d: 0.0,
                vel_n: 0.0,
                vel_e: 0.0,
                vel_d: 0.0,
                wx: 0.0,
                wy: 0.0,
                wz: 0.0,
                bgx: 0.0,
                bgy: 0.0,
                bgz: 0.0,
                innovation: 0.0,
                failed_rotor: 0xFF,
                mode: 0,
                failsafe: 0,
                valid: 0,
                tick_tail: 0,
            },
        }
    }
}

impl PilotGuest for Component {
    /// See `cascade`'s `configure_supervisor`: store, and drop the supervisor —
    /// which in `cascade` drops the core with it, so here the next call
    /// rebuilds both partitions too.
    fn configure_supervisor(cfg: SupervisorConfig) {
        *SUPCFG.0.borrow_mut() = Some(cfg);
        *CORE.0.borrow_mut() = None;
    }

    /// See `cascade`'s `command`.
    fn command(cmd: PilotCommand, level: bool, throttle_low: bool) {
        use falcon_core::relay_fsm::Event;
        // EXHAUSTIVE on purpose — no `_` arm (see `cascade`).
        let ev = match cmd {
            PilotCommand::Arm => Event::Arm,
            PilotCommand::RequestTakeoff => Event::RequestTakeoff,
            PilotCommand::RequestMission => Event::RequestMission,
            PilotCommand::RequestLoiter => Event::RequestLoiter,
            PilotCommand::RequestRtl => Event::RequestRtl,
            PilotCommand::RequestLand => Event::RequestLand,
            PilotCommand::RequestDisarm => Event::RequestDisarm,
            PilotCommand::Terminate => Event::Terminate,
        };

        let mut guard = CORE.0.borrow_mut();
        let cfg = CONFIG.0.borrow();
        let supcfg = SUPCFG.0.borrow();
        let sup = ensure_supervisor(&mut guard, cfg.as_ref(), supcfg.as_ref());
        sup.command(ev, level, throttle_low);
    }
}

