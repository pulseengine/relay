//! cascade-split — the SUPERVISED vehicle, driving two partition components
//! (#575).
//!
//! The same vehicle as `wasm/cm/cascade`, deployed as three components instead
//! of one: this orchestrator holds `falcon_core::FlightSupervisor`, and the
//! flight core it supervises is the pair `cascade-estimator` +
//! `cascade-control`, imported through the `estimator` and `flight-control`
//! interfaces and joined by the `nav-state` seam. `wac plug` composes the three;
//! the result exports `controller`, `observer` and `pilot`, exactly as `cascade`
//! does.
//!
//! WHY THE SUPERVISOR IS HERE (maintainer decision on #575, option 1). A split
//! that wrapped only the two partitions would have no mode machine, no failsafe
//! arbiter and no pre-arm rows: "a stabiliser with no supervisor", #414 again.
//! So this component depends on falcon-core, and the supervisor drives the
//! remote halves through `falcon_core::SupervisedCore` — the trait that names
//! exactly the calls `FlightSupervisor` makes on its core. [`RemoteCore`] is
//! the implementation that forwards each of them across the seam.
//!
//! THIS FILE MIRRORS `wasm/cm/cascade/src/lib.rs` and must keep doing so. The
//! seam logic — sanitising, the unconfigured-supervisor sentinels, the
//! `FailsafeConfigured` re-declaration, the published state and its `valid`
//! bits, the pilot command mapping — is the monolithic component's, line for
//! line, and the rationale for each piece is written down THERE rather than
//! restated here. What differs is only where the core lives. The DRIFT GATE is
//! the differential in `tests/cascade-sitl-wasm` (`SPLIT=<composed.wasm>`): the
//! two components must agree bit for bit on every motor command and every
//! published field, every tick, or it fails.

#[cfg(not(feature = "std"))]
compile_error!(
    "the no_std build of the cascade-split components waits on #574 (arena \
     reclamation): every seam call spills through cabi_realloc and the bump \
     arena cannot reclaim it"
);

