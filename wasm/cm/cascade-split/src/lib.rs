//! cascade-split — the SUPERVISED vehicle, driving two partition components
//! (#575).
//!
//! The same vehicle as `wasm/cm/cascade`, deployed as three components instead
//! of one: this orchestrator holds `falcon_core::FlightSupervisor`, and the
//! flight core it supervises is the pair `cascade-estimator` +
//! `cascade-control`, imported through the `estimator` and `flight-control`
//! interfaces and joined by the `nav-state` seam. `wac plug` composes the three;
//! the result exports `controller`, `observer` and `pilot`, exactly as `cascade`
//! does.
//!
//! WHY THE SUPERVISOR IS HERE (maintainer decision on #575, option 1). A split
//! that wrapped only the two partitions would have no mode machine, no failsafe
//! arbiter and no pre-arm rows: "a stabiliser with no supervisor", #414 again.
//! So this component depends on falcon-core, and the supervisor drives the
//! remote halves through `falcon_core::SupervisedCore`, the trait that names
//! exactly the calls `FlightSupervisor` makes on its core.
//!
//! THIS FILE DOES NOT IMPLEMENT THE SEAM'S RULES (#609 single-source refactor).
//! Which configuration is usable, when a configure may rebuild the supervisor,
//! which pre-arm rows a fresh supervisor declares failing, and how a
//! calibration survives a rebuild are `falcon_core::host::SupervisorHost` —
//! the SAME code the published `cascade` runs, here instantiated over
//! `falcon_core::split::SplitCore` instead of the fused `FlightCore`. The one
//! per-core step, building a fresh core with the tuning, is
//! `HostCore for SplitCore`: it resets BOTH partitions (`estimator.configure`,
//! `flight-control.configure`) with the validated tuning, verbatim. What
//! remains here is the ABI: WIT records copied field for field, the partition
//! imports behind `PartitionSeam` ([`WitSeam`]), and the published state.
//!
//! THE CALIBRATION reaches BOTH partitions: the host installs it through
//! `FlightSupervisor::set_calibration`, which calls `SplitCore::set_calibration`
//! (`estimator.configure-calibration` + `flight-control.configure-calibration`),
//! and re-installs it after every rebuild. `CalibrationPresent` is the
//! supervisor's own "a VALID calibration was configured" flag (the identity
//! included), exactly as in `cascade`.
//!
//! THE DRIFT GATE is the twin differential in `tests/cascade-sitl-wasm`
//! (`DIFF_AGAINST=<composed.wasm>`): the two components must agree bit for bit
//! on every motor command and every published field, every tick. The #609
//! lifecycle tests in `tests/cascade-sitl-wasm/src/seam_tests.rs` run against
//! this component as well as against `cascade` (`CASCADE_SPLIT_WASM`), and
//! `crates/falcon-core/tests/supervised_core_split.rs` drives
//! `SupervisorHost<SplitCore<_>>` against `SupervisorHost<FlightCore>` in CI.

#![cfg_attr(not(feature = "std"), no_std)]

