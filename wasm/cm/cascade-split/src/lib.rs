/// The flight core the supervisor drives: falcon-core's `SplitCore` — the
/// forwarding, including the #452 edge and the estimate-only path — over the
/// WIT imports. This file adds only the WIT encoding ([`WitSeam`]).
type RemoteCore = SplitCore<WitSeam>;

/// The twelve seam calls, as WIT imports. Zero-sized: the state lives in
/// `cascade-estimator` and `cascade-control`. Pure encoding, no logic.
#[derive(Default)]
struct WitSeam;

fn nav_from_wit(n: WitNav) -> NavState {
    NavState {
        q: [n.qw, n.qx, n.qy, n.qz],
        v: [n.vel_n, n.vel_e, n.vel_d],
        p: [n.pos_n, n.pos_e, n.pos_d],
        b_g: [n.bgx, n.bgy, n.bgz],
        b_a: [n.bax, n.bay, n.baz],
    }
}

fn nav_to_wit(n: &NavState) -> WitNav {
    WitNav {
        qw: n.q[0],
        qx: n.q[1],
        qy: n.q[2],
        qz: n.q[3],
        vel_n: n.v[0],
        vel_e: n.v[1],
        vel_d: n.v[2],
        pos_n: n.p[0],
        pos_e: n.p[1],
        pos_d: n.p[2],
        bgx: n.b_g[0],
        bgy: n.b_g[1],
        bgz: n.b_g[2],
        bax: n.b_a[0],
        bay: n.b_a[1],
        baz: n.b_a[2],
    }
}

fn v3(v: Vec3) -> WitVec3 {
    WitVec3 {
        x: v[0],
        y: v[1],
        z: v[2],
    }
}

fn imu_to_wit(i: CoreImu) -> WitImu {
    WitImu {
        ax: i.accel[0],
        ay: i.accel[1],
        az: i.accel[2],
        gx: i.gyro[0],
        gy: i.gyro[1],
        gz: i.gyro[2],
    }
}

fn frame_to_wit(f: &SeamFrame) -> SensorFrame {
    SensorFrame {
        imu: imu_to_wit(f.imu),
        dt_s: f.dt,
        position_ned: f.position.map(v3),
        mag_body: f.mag.map(v3),
        heading_rad: f.heading,
        motor_rpm: f.motor_rpm.map(|r| RotorRpm {
            m1: r[0],
            m2: r[1],
            m3: r[2],
            m4: r[3],
        }),
        battery_v: f.battery_v,
    }
}

/// `CalParams` -> the seam record, all six fields (`mag-offdiag` included).
fn cal_to_wit(c: &CalParams) -> CalibrationParams {
    CalibrationParams {
        gyro_bias: v3(c.gyro_bias),
        accel_bias: v3(c.accel_bias),
        accel_scale: v3(c.accel_scale),
        mag_offset: v3(c.mag_offset),
        mag_scale: v3(c.mag_scale),
        mag_offdiag: v3(c.mag_offdiag),
    }
}

fn cal_from_wit(c: CalibrationParams) -> CalParams {
    let v = |a: WitVec3| [a.x, a.y, a.z];
    CalParams {
        gyro_bias: v(c.gyro_bias),
        accel_bias: v(c.accel_bias),
        accel_scale: v(c.accel_scale),
        mag_offset: v(c.mag_offset),
        mag_scale: v(c.mag_scale),
        mag_offdiag: v(c.mag_offdiag),
    }
}

impl PartitionSeam for WitSeam {
    /// Rebuild BOTH partitions with their share of the (already validated)
    /// tuning, verbatim; `None` = their built-in defaults.
    fn reset_partitions(&mut self, tuning: Option<&VehicleTuning>) {
        estimator::configure(tuning.map(|t| {
            let e = split::estimator_tuning(t);
            EstimatorConfig {
                pos_var: e.pos_var,
                process_floor_vel: e.process_floor_vel,
                process_floor_pos: e.process_floor_pos,
            }
        }));
        flight_control::configure(tuning.map(|t| {
            let c = split::control_tuning(t);
            ControlConfig {
                hover_thrust: c.hover_thrust,
                altitude_kp: c.altitude_kp,
                altitude_kd: c.altitude_kd,
                altitude_ki: c.altitude_ki,
                position_ki: c.position_ki,
            }
        }));
    }
    fn estimator_tick(&mut self, f: &SeamFrame, in_flight: Option<bool>) -> NavState {
        nav_from_wit(estimator::tick(frame_to_wit(f), in_flight))
    }
    fn estimator_nav(&self) -> NavState {
        nav_from_wit(estimator::read_nav())
    }
    fn estimator_health(&self) -> EstimatorHealth {
        let h = estimator::read_health();
        EstimatorHealth {
            tilt_uncertainty: h.tilt_uncertainty,
            nav_compromised: h.nav_compromised,
            gnss_diverged: h.gnss_diverged,
        }
    }
    fn control_tick(&mut self, nav: &NavState, f: &SeamFrame) -> [f32; 4] {
        let o = flight_control::tick(nav_to_wit(nav), frame_to_wit(f));
        [o.m1, o.m2, o.m3, o.m4]
    }
    fn control_keep_warm(&mut self, imu: CoreImu) {
        flight_control::keep_warm(imu_to_wit(imu));
    }
    fn control_set_position(&mut self, ned: Vec3) {
        flight_control::set_position(v3(ned));
    }
    fn control_set_landing(&mut self, on: bool) {
        flight_control::set_landing(on);
    }
    fn control_status(&self) -> ControlStatus {
        let s = flight_control::read_status();
        ControlStatus {
            flying: s.flying,
            max_motor: s.max_motor,
            failed_rotor: match s.failed_rotor {
                0xFF => None,
                i => Some(i as usize),
            },
        }
    }
    fn estimator_set_calibration(&mut self, c: CalParams) {
        estimator::configure_calibration(cal_to_wit(&c));
    }
    fn estimator_calibration(&self) -> CalParams {
        cal_from_wit(estimator::read_calibration())
    }
    fn control_set_calibration(&mut self, c: CalParams) {
        flight_control::configure_calibration(cal_to_wit(&c));
    }
}

// ── from here on: `cascade`'s adapter, with `RemoteCore` as the core ────────

/// THE SUPERVISOR AND EVERYTHING IT IS BUILT FROM — falcon-core's
/// `SupervisorHost`, over the split core. See `cascade`'s `HOST`. Building or
/// rebuilding the supervisor rebuilds both partitions (the per-core hook).
static HOST: SingleThreaded<SupervisorHost<RemoteCore>> =
    SingleThreaded(RefCell::new(SupervisorHost::new()));

/// See `cascade`'s `PUBLISHED`. The tick is monotonic and NOT reset by either
/// configure call.
static PUBLISHED: SingleThreaded<Option<PublishedState>> = SingleThreaded(RefCell::new(None));

#[derive(Clone, Copy)]
struct PublishedState {
    tick: u32,
    q: [f32; 4],
    p: [f32; 3],
    v: [f32; 3],
    w: [f32; 3],
    bg: [f32; 3],
    innovation: f32,
    failed_rotor: u8,
    mode: u8,
    failsafe: u32,
    valid: u32,
}

/// `valid` bits. A CLEAR bit means NOT MEASURED — never "the value is zero".
const V_ATT: u32 = 1 << 0;
const V_POS: u32 = 1 << 1;
const V_VEL: u32 = 1 << 2;
const V_RATE: u32 = 1 << 3;
const V_BIAS: u32 = 1 << 4;
const V_INNOV: u32 = 1 << 5;
const V_ROTOR: u32 = 1 << 6;
const V_MODE: u32 = 1 << 7;
const V_FAILSAFE: u32 = 1 << 8;

/// See `cascade`'s `vehicle_config`: field for field, never validated here.
fn vehicle_config(c: &VehicleConfig) -> host::VehicleConfig {
    host::VehicleConfig {
        hover_thrust: c.hover_thrust,
        loop_rate_hz: c.loop_rate_hz,
        pos_var: c.pos_var,
        process_floor_vel: c.process_floor_vel,
        process_floor_pos: c.process_floor_pos,
        altitude_kp: c.altitude_kp,
        altitude_kd: c.altitude_kd,
        altitude_ki: c.altitude_ki,
        position_ki: c.position_ki,
    }
}

/// See `cascade`'s `supervisor_config`: field for field.
fn supervisor_config(c: &SupervisorConfig) -> host::SupervisorConfig {
    host::SupervisorConfig {
        home: [c.home.x, c.home.y, c.home.z],
        fence_radius: c.fence_radius,
        cruise_alt: c.cruise_alt,
        low_batt_v: c.low_batt_v,
    }
}

/// See `cascade`'s `cal_params`: field for field, `mag-offdiag` included.
fn cal_params(c: &SensorCalibration) -> CalParams {
    let v = |a: &WitVec3| [a.x, a.y, a.z];
    CalParams {
        gyro_bias: v(&c.gyro_bias),
        accel_bias: v(&c.accel_bias),
        accel_scale: v(&c.accel_scale),
        mag_offset: v(&c.mag_offset),
        mag_scale: v(&c.mag_scale),
        mag_offdiag: v(&c.mag_offdiag),
    }
}

struct Component;

impl Guest for Component {
    /// See `cascade`'s `step`.
    fn step(sensors: SensorFrame, target: Waypoint) -> MotorPwm {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        let dt = if sensors.dt_s.is_finite() {
            sensors.dt_s.clamp(0.0001, 0.1)
        } else {
            0.001
        };

        let imu = sensors.imu;
        // The frame as the backend's answers, the motor command caught on the
        // way out — falcon-core's `FrameBackend`, so the CI-run test drives the
        // supervisor through the same type.
        let mut backend = FrameBackend::new(SeamFrame {
            imu: CoreImu {
                accel: [imu.ax, imu.ay, imu.az],
                gyro: [imu.gx, imu.gy, imu.gz],
            },
            dt,
            position: sensors.position_ned.map(|p| [p.x, p.y, p.z]),
            mag: sensors.mag_body.map(|m| [m.x, m.y, m.z]),
            heading: sensors.heading_rad,
            motor_rpm: sensors.motor_rpm.map(|r| [r.m1, r.m2, r.m3, r.m4]),
            battery_v: sensors.battery_v,
        });

        {
            let mut host = HOST.0.borrow_mut();
            // `target` is a MISSION LEG at @0.12.0 — see `cascade`.
            let sup = host.step([target.north, target.east, target.down], &mut backend);

            let ns = sup.state();
            let failed = sup.core().failed_motor();
            let mode = sup.mode() as u8;
            let failsafe = sup.failsafe_flags();
            let mut prev = PUBLISHED.0.borrow_mut();
            let tick = prev.as_ref().map(|s| s.tick.wrapping_add(1)).unwrap_or(0);
            let valid =
                V_ATT | V_POS | V_VEL | V_RATE | V_BIAS | V_INNOV | V_ROTOR | V_MODE | V_FAILSAFE;
            *prev = Some(PublishedState {
                tick,
                q: ns.q,
                p: ns.p,
                v: ns.v,
                w: [imu.gx, imu.gy, imu.gz],
                bg: ns.b_g,
                innovation: 0.0,
                failed_rotor: failed.map(|i| i as u8).unwrap_or(0xFF),
                mode,
                failsafe,
                valid,
            });
        }

        MotorPwm {
            m1: backend.motors[0],
            m2: backend.motors[1],
            m3: backend.motors[2],
            m4: backend.motors[3],
        }
    }

    /// See `cascade`'s `configure` (`SupervisorHost::configure_vehicle`).
    fn configure(cfg: VehicleConfig) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        HOST.0.borrow_mut().configure_vehicle(vehicle_config(&cfg));
    }
}

impl ObserverGuest for Component {
    /// See `cascade`'s `read_state`.
    fn read_state() -> FlightState {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();
        let s = PUBLISHED.0.borrow();
        match s.as_ref() {
            Some(p) => FlightState {
                tick_head: p.tick,
                qw: p.q[0],
                qx: p.q[1],
                qy: p.q[2],
                qz: p.q[3],
                pos_n: p.p[0],
                pos_e: p.p[1],
                pos_d: p.p[2],
                vel_n: p.v[0],
                vel_e: p.v[1],
                vel_d: p.v[2],
                wx: p.w[0],
                wy: p.w[1],
                wz: p.w[2],
                bgx: p.bg[0],
                bgy: p.bg[1],
                bgz: p.bg[2],
                innovation: p.innovation,
                failed_rotor: p.failed_rotor,
                mode: p.mode,
                failsafe: p.failsafe,
                valid: p.valid,
                tick_tail: p.tick,
            },
            // NO TICK HAS RUN: `valid` is 0 and `mode` 0 is NOT `disarmed`.
            None => FlightState {
                tick_head: 0,
                qw: 1.0,
                qx: 0.0,
                qy: 0.0,
                qz: 0.0,
                pos_n: 0.0,
                pos_e: 0.0,
                pos_d: 0.0,
                vel_n: 0.0,
                vel_e: 0.0,
                vel_d: 0.0,
                wx: 0.0,
                wy: 0.0,
                wz: 0.0,
                bgx: 0.0,
                bgy: 0.0,
                bgz: 0.0,
                innovation: 0.0,
                failed_rotor: 0xFF,
                mode: 0,
                failsafe: 0,
                valid: 0,
                tick_tail: 0,
            },
        }
    }
}

impl PilotGuest for Component {
    /// See `cascade`'s `configure_supervisor`
    /// (`SupervisorHost::configure_supervisor`).
    fn configure_supervisor(cfg: SupervisorConfig) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        HOST.0
            .borrow_mut()
            .configure_supervisor(supervisor_config(&cfg));
    }

    /// See `cascade`'s `configure_calibration`
    /// (`SupervisorHost::configure_calibration`). Installed through
    /// `FlightSupervisor::set_calibration` -> `SplitCore::set_calibration`, i.e.
    /// on BOTH partitions in one call.
    fn configure_calibration(cal: SensorCalibration) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        HOST.0.borrow_mut().configure_calibration(cal_params(&cal));
    }

    /// See `cascade`'s `command`.
    fn command(cmd: PilotCommand, level: bool, throttle_low: bool) {
        #[cfg(not(feature = "std"))]
        let _call = falcon_cm_rt::CallScope::enter();

        use falcon_core::relay_fsm::Event;
        // EXHAUSTIVE on purpose — no `_` arm (see `cascade`).
        let ev = match cmd {
            PilotCommand::Arm => Event::Arm,
            PilotCommand::RequestTakeoff => Event::RequestTakeoff,
            PilotCommand::RequestMission => Event::RequestMission,
            PilotCommand::RequestLoiter => Event::RequestLoiter,
            PilotCommand::RequestRtl => Event::RequestRtl,
            PilotCommand::RequestLand => Event::RequestLand,
            PilotCommand::RequestDisarm => Event::RequestDisarm,
            PilotCommand::Terminate => Event::Terminate,
        };

        HOST.0.borrow_mut().command(ev, level, throttle_low);
    }
}

