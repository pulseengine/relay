//! cascade-estimator — falcon-core's ESTIMATOR PARTITION as one component (#575).
//!
//! One half of the `cascade-split` deployment. It wraps
//! `falcon_core::EstimatorPartition` — IEKF propagate plus every measurement
//! update — and nothing else. The supervisor is NOT here: it lives in the
//! `cascade-split` orchestrator.
//!
//! A THIN WIT ADAPTER. What this partition does behind the seam is
//! `falcon_core::split::{estimator_tick, estimator_health, ...}` — the same
//! functions the CI-run test `crates/falcon-core/tests/supervised_core_split.rs`
//! drives in process. This file only converts WIT records to and from them.

#![cfg_attr(not(feature = "std"), no_std)]

// Bounded work-memory arena + `cabi_realloc` + panic handler, exactly as the
// monolithic `cascade` links them (crates/falcon-cm-rt). The no_std build is
// the one meld can fuse into ONE shared memory: no wasi-libc, no allocator
// that grows, so no `memory.grow`.
//
// ARENA RECLAMATION. Every export below calls `BumpArena::reset()` FIRST. That
// is sound for the same reason it is in `cascade`: the canonical ABI allocates
// here only for a call's spilled parameter area, which wit-bindgen's export
// glue has already LIFTED into locals before the body runs, so nothing in the
// arena outlives the call that allocated it. (#574 replaces this pattern with
// a scoped `CallScope`; every reset below is one of its migration points.)
#[cfg(not(feature = "std"))]
falcon_cm_rt::export_cm_rt!();

/// Reclaim the previous call's parameter area. A no-op on the std build.
#[inline(always)]
fn reset_arena() {
    #[cfg(not(feature = "std"))]
    falcon_cm_rt::BumpArena::reset();
}

// Bindings generated by cargo-component as src/bindings.rs.
#[allow(warnings)]
mod bindings;

use bindings::exports::pulseengine::falcon_cascade::estimator::Guest;
use bindings::pulseengine::falcon_cascade::types::{
    CalibrationParams, EstimatorConfig, EstimatorHealth, NavState as WitNav, SensorFrame,
    Vec3 as WitVec3,
};

use core::cell::RefCell;
use falcon_core::split::{self, EstimatorTuning, SeamFrame};
use falcon_core::{EstimatorPartition, ImuSample as CoreImu, NavState};

struct SingleThreaded<T>(RefCell<T>);
// SAFETY: the component model guarantees single-threaded, non-reentrant access.
unsafe impl<T> Sync for SingleThreaded<T> {}

/// The partition, built lazily by `split::new_estimator` — from the same
/// numbers `FlightSupervisor::new` builds its core from.
static EST: SingleThreaded<Option<EstimatorPartition>> = SingleThreaded(RefCell::new(None));

fn ensure(slot: &mut Option<EstimatorPartition>) -> &mut EstimatorPartition {
    slot.get_or_insert_with(split::new_estimator)
}

/// The seam frame, as falcon-core's `SeamFrame`.
fn seam_frame(f: SensorFrame) -> SeamFrame {
    let i = f.imu;
    SeamFrame {
        imu: CoreImu {
            accel: [i.ax, i.ay, i.az],
            gyro: [i.gx, i.gy, i.gz],
        },
        dt: f.dt_s,
        position: f.position_ned.map(|p| [p.x, p.y, p.z]),
        mag: f.mag_body.map(|m| [m.x, m.y, m.z]),
        heading: f.heading_rad,
        motor_rpm: f.motor_rpm.map(|r| [r.m1, r.m2, r.m3, r.m4]),
        battery_v: f.battery_v,
    }
}

fn to_wit(n: NavState) -> WitNav {
    WitNav {
        qw: n.q[0],
        qx: n.q[1],
        qy: n.q[2],
        qz: n.q[3],
        vel_n: n.v[0],
        vel_e: n.v[1],
        vel_d: n.v[2],
        pos_n: n.p[0],
        pos_e: n.p[1],
        pos_d: n.p[2],
        bgx: n.b_g[0],
        bgy: n.b_g[1],
        bgz: n.b_g[2],
        bax: n.b_a[0],
        bay: n.b_a[1],
        baz: n.b_a[2],
    }
}

/// The seam's `calibration-params` as falcon-core's `CalParams`, field for
/// field. Already validated by the orchestrator, so nothing is checked here.
fn cal_from_wit(c: CalibrationParams) -> falcon_core::relay_calib::CalParams {
    let v = |a: WitVec3| [a.x, a.y, a.z];
    falcon_core::relay_calib::CalParams {
        gyro_bias: v(c.gyro_bias),
        accel_bias: v(c.accel_bias),
        accel_scale: v(c.accel_scale),
        mag_offset: v(c.mag_offset),
        mag_scale: v(c.mag_scale),
    }
}

fn cal_to_wit(c: falcon_core::relay_calib::CalParams) -> CalibrationParams {
    let v = |a: [f32; 3]| WitVec3 {
        x: a[0],
        y: a[1],
        z: a[2],
    };
    CalibrationParams {
        gyro_bias: v(c.gyro_bias),
        accel_bias: v(c.accel_bias),
        accel_scale: v(c.accel_scale),
        mag_offset: v(c.mag_offset),
        mag_scale: v(c.mag_scale),
    }
}

struct Component;

impl Guest for Component {
    /// Rebuild THIS partition, dropping only its state, then apply the
    /// (already sanitised) tuning.
    fn configure(cfg: Option<EstimatorConfig>) {
        reset_arena();
        let mut slot = EST.0.borrow_mut();
        *slot = None;
        let est = ensure(&mut slot);
        if let Some(c) = cfg {
            split::apply_estimator_tuning(
                est,
                &EstimatorTuning {
                    pos_var: c.pos_var,
                    process_floor_vel: c.process_floor_vel,
                    process_floor_pos: c.process_floor_pos,
                },
            );
        }
    }

    fn tick(sensors: SensorFrame, in_flight: Option<bool>) -> WitNav {
        reset_arena();
        let mut slot = EST.0.borrow_mut();
        to_wit(split::estimator_tick(
            ensure(&mut slot),
            &seam_frame(sensors),
            in_flight,
        ))
    }

    fn read_nav() -> WitNav {
        reset_arena();
        let mut slot = EST.0.borrow_mut();
        to_wit(ensure(&mut slot).state())
    }

    fn read_health() -> EstimatorHealth {
        reset_arena();
        let mut slot = EST.0.borrow_mut();
        let h = split::estimator_health(ensure(&mut slot));
        EstimatorHealth {
            tilt_uncertainty: h.tilt_uncertainty,
            nav_compromised: h.nav_compromised,
            gnss_diverged: h.gnss_diverged,
        }
    }

    /// In place: resets nothing (#586). A rebuild by `configure` returns the
    /// partition to the identity, and the orchestrator re-sends it.
    fn configure_calibration(cal: CalibrationParams) {
        reset_arena();
        let mut slot = EST.0.borrow_mut();
        split::estimator_set_calibration(ensure(&mut slot), cal_from_wit(cal));
    }

    fn read_calibration() -> CalibrationParams {
        reset_arena();
        let mut slot = EST.0.borrow_mut();
        cal_to_wit(split::estimator_calibration(ensure(&mut slot)))
    }
}

bindings::export!(Component with_types_in bindings);
