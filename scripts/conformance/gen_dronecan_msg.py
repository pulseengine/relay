import json, random, sys
from dronecan import uavcan

SEED = 20240611
rng = random.Random(SEED)
skipped = {'node_status': 0, 'raw_command': 0}
counters = {'rt_errors': 0}
ns_vecs = []
rc_vecs = []


def wire(m):
    b = m._pack(True)
    b += '0' * ((8 - len(b) % 8) % 8)
    return bytes(int(b[i:i + 8], 2) for i in range(0, len(b), 8))


def rt(cls, by):
    m = cls()
    m._unpack(''.join(f'{x:08b}' for x in by), True)
    return m


def hexarr(by):
    return '&[' + ', '.join('0x%02X' % x for x in by) + ']'


def mk_ns(u, h, mo, sm, v):
    try:
        m = uavcan.protocol.NodeStatus()
        m.uptime_sec = u
        m.health = h
        m.mode = mo
        m.sub_mode = sm
        m.vendor_specific_status_code = v
        by = wire(m)
        if len(by) != 7:
            raise ValueError('len')
        got = None
        try:
            r = rt(uavcan.protocol.NodeStatus, by)
            got = (int(r.uptime_sec), int(r.health), int(r.mode), int(r.sub_mode), int(r.vendor_specific_status_code))
        except Exception:
            counters['rt_errors'] += 1
        if got is not None and got != (u, h, mo, sm, v):
            raise ValueError('rt mismatch')
        ns_vecs.append((by, (u, h, mo, sm, v)))
    except Exception:
        skipped['node_status'] += 1


def mk_rc(cmd):
    try:
        m = uavcan.equipment.esc.RawCommand()
        m.cmd = list(cmd)
        by = wire(m)
        if len(by) != (14 * len(cmd) + 7) // 8:
            raise ValueError('len')
        if cmd:
            got = None
            try:
                r = rt(uavcan.equipment.esc.RawCommand, by)
                got = [int(x) for x in r.cmd]
            except Exception:
                counters['rt_errors'] += 1
            if got is not None and got != list(cmd):
                raise ValueError('rt mismatch')
        rc_vecs.append((by, list(cmd)))
    except Exception:
        skipped['raw_command'] += 1


def pw(bits):
    s = set()
    for k in range(bits + 1):
        s.add((1 << k) - 1)
        if k < bits:
            s.add(1 << k)
    return sorted(s)


U = sorted(set(pw(32)) | {2, 255, 256, 65535, 65536, 0x7FFFFFFF, 0x80000000})
V = sorted(set(pw(16)) | {2, 255, 256, 0x7FFF, 0x8000})

# NodeStatus: fixed boundaries
mk_ns(0, 0, 0, 0, 0)
mk_ns(0xFFFFFFFF, 3, 7, 7, 0xFFFF)
for u in U:
    mk_ns(u, 0, 0, 0, 0)
    mk_ns(u, 3, 7, 7, 0xFFFF)
for v in V:
    mk_ns(1, 1, 1, 1, v)
idx = 0
for h in range(4):
    for mo in range(8):
        for sm in range(8):
            mk_ns(U[idx % len(U)], h, mo, sm, V[(idx * 7) % len(V)])
            idx += 1
# NodeStatus: seeded random
for _ in range(30):
    mk_ns(rng.getrandbits(32), rng.randrange(4), rng.randrange(8), rng.randrange(8), rng.getrandbits(16))

# RawCommand
LO, HI = -8192, 8191
B = [LO, -1, 0, 1, HI]
E = set()
for k in range(1, 14):
    for x in (1 << k, (1 << k) - 1, -(1 << k), -(1 << k) - 1):
        if LO <= x <= HI:
            E.add(x)
E |= {LO + 1, HI - 1}
E = sorted(E)
mk_rc([])
for n in range(1, 21):
    for b in B:
        mk_rc([b] * n)
    mk_rc([B[(i + n) % 5] for i in range(n)])
for x in E:
    mk_rc([x])
    mk_rc([0, x, 0])
for _ in range(120):
    n = rng.randint(0, 20)
    mk_rc([rng.choice(B) if rng.random() < 0.3 else rng.randint(LO, HI) for _ in range(n)])

# Negative cases: truncated NodeStatus payloads
shorts = []
if ns_vecs:
    picks = rng.sample(range(len(ns_vecs)), min(4, len(ns_vecs)))
    for i in picks:
        for L in range(7):
            shorts.append(ns_vecs[i][0][:L])

print('// Generated by scripts/conformance/gen_dronecan_msg.py, seed %d. Do not edit.' % SEED)
print('#[allow(dead_code)]')
print('#[derive(Debug, Clone, Copy)]')
print("pub struct NsVec { pub bytes: &'static [u8], pub uptime_sec: u32, pub health: u8, pub mode: u8, pub sub_mode: u8, pub vendor: u16 }")
print('#[allow(dead_code)]')
print('#[derive(Debug, Clone, Copy)]')
print("pub struct RcVec { pub bytes: &'static [u8], pub cmd: &'static [i16] }")
print('pub static NS_VECTORS: &[NsVec] = &[')
for by, (u, h, mo, sm, v) in ns_vecs:
    print('    NsVec { bytes: %s, uptime_sec: %d, health: %d, mode: %d, sub_mode: %d, vendor: %d },' % (hexarr(by), u, h, mo, sm, v))
print('];')
print('pub static RC_VECTORS: &[RcVec] = &[')
for by, cmd in rc_vecs:
    print('    RcVec { bytes: %s, cmd: &[%s] },' % (hexarr(by), ', '.join(str(x) for x in cmd)))
print('];')
print('pub static NS_SHORT: &[&[u8]] = &[')
for s in shorts:
    print('    %s,' % hexarr(s))
print('];')


def cov(vals, hi, lo=None):
    d = {'n': len(vals), 'zero': sum(1 for x in vals if x == 0), 'max': sum(1 for x in vals if x == hi)}
    if lo is not None:
        d['neg'] = sum(1 for x in vals if x < 0)
        d['min'] = sum(1 for x in vals if x == lo)
    return d


report = {
    'node_status.uptime_sec': cov([t[1][0] for t in ns_vecs], 0xFFFFFFFF),
    'node_status.health': cov([t[1][1] for t in ns_vecs], 3),
    'node_status.mode': cov([t[1][2] for t in ns_vecs], 7),
    'node_status.sub_mode': cov([t[1][3] for t in ns_vecs], 7),
    'node_status.vendor_status': cov([t[1][4] for t in ns_vecs], 0xFFFF),
    'raw_command.cmd': cov([x for t in rc_vecs for x in t[1]], HI, LO),
    'raw_command.count': cov([len(t[1]) for t in rc_vecs], 20),
    'node_status_short': {'n': len(shorts), 'neg': 0, 'zero': 0, 'min': 0, 'max': 0},
    'skipped': skipped,
    'rt_errors': counters['rt_errors'],
    'seed': SEED,
}
print(json.dumps(report, sort_keys=True), file=sys.stderr)
