import sys, json, random, struct
from pyubx2 import UBXMessage, UBXReader, GET

SEED = 20240607
rng = random.Random(SEED)
skipped = 0
I32F = ['lat', 'lon', 'height', 'hMSL', 'velN', 'velE', 'velD']
OFF = {'lon': 24, 'lat': 28, 'height': 32, 'hMSL': 36, 'velN': 48, 'velE': 52, 'velD': 56}
BND = [-2**31, 2**31 - 1, -1, 0, 1, 255, 256, -256, 65535, 65536, -65536, 2**23 - 1, -2**23, 2**30, -2**30, 2**31 - 2, -2**31 + 1, 1000, -1000]
FT = [0, 1, 2, 3, 4, 5, 255]
NSV = [0, 1, 2, 12, 32, 128, 254, 255]

def ri():
    if rng.random() < 0.3:
        return rng.randint(-100000, 100000)
    return rng.randint(-2**31, 2**31 - 1)

def base():
    d = {f: ri() for f in I32F}
    d['fixType'] = rng.choice([0, 1, 2, 3, 3, 3, 4, 5, rng.randint(0, 255)])
    d['numSV'] = rng.choice([0, 4, 8, 12, 20, rng.randint(0, 255)])
    return d

def payload(d):
    p = bytearray(rng.randint(0, 255) for _ in range(92))
    struct.pack_into('<H', p, 4, rng.randint(1999, 2099))
    for f in I32F:
        struct.pack_into('<i', p, OFF[f], d[f])
    p[20] = d['fixType']
    p[23] = d['numSV']
    return bytes(p)

def frame(cls, mid, pl):
    return UBXMessage(cls, mid, GET, payload=pl).serialize()

def parse(f):
    return UBXReader.parse(f)

# determine library scaling per field using a probe
scale = {}
try:
    pd = {f: 1234567 for f in I32F}
    pd['fixType'] = 3
    pd['numSV'] = 9
    pp = parse(frame('NAV', 'NAV-PVT', payload(pd)))
    for f in I32F:
        v = getattr(pp, f)
        for s in (1, 1e-1, 1e-2, 1e-3, 1e-5, 1e-7):
            if int(round(v / s)) == 1234567:
                scale[f] = s
                break
except Exception as e:
    sys.stderr.write('probe failed: %r\n' % (e,))

def lib_vals(f):
    p = parse(f)
    r = {}
    for k in I32F:
        r[k] = int(round(getattr(p, k) / scale[k]))
    r['fixType'] = int(p.fixType)
    r['numSV'] = int(p.numSV)
    return r

specs = []
for f in I32F:
    for b in BND:
        d = base(); d[f] = b; specs.append(d)
for v in FT:
    d = base(); d['fixType'] = v; specs.append(d)
for v in NSV:
    d = base(); d['numSV'] = v; specs.append(d)
for val, ft in ((0, 0), (-2**31, 255), (2**31 - 1, 255)):
    d = {f: val for f in I32F}; d['fixType'] = ft; d['numSV'] = ft; specs.append(d)
for _ in range(160):
    specs.append(base())

rows = []
if len(scale) == len(I32F):
    for d in specs:
        try:
            f = frame('NAV', 'NAV-PVT', payload(d))
            if len(f) != 100:
                raise ValueError('len')
            rows.append((lib_vals(f), f))
        except Exception:
            skipped += 1
else:
    skipped += len(specs)

others = []
for _ in range(4):
    for cls, mid, n in (('NAV', 'NAV-STATUS', 16), ('NAV', 'NAV-POSLLH', 28)):
        try:
            others.append(frame(cls, mid, bytes(rng.randint(0, 255) for _ in range(n))))
        except Exception:
            skipped += 1

def garbage():
    return bytes(rng.choice([x for x in range(256) if x != 0xB5]) for _ in range(rng.randint(0, 20)))

def bad(f):
    b = bytearray(f)
    b[-1] ^= rng.randint(1, 255)
    return bytes(b)

streams = []
if rows:
    N = len(rows)
    for _ in range(90):
        kind = rng.randrange(7)
        buf = bytearray(); exp = []
        if kind == 0:
            i = rng.randrange(N); buf += garbage() + rows[i][1]; exp = [i]
        elif kind == 1:
            for _ in range(rng.randint(2, 5)):
                i = rng.randrange(N); buf += rows[i][1]; exp.append(i)
        elif kind == 2 and others:
            for _ in range(rng.randint(1, 3)):
                buf += rng.choice(others)
                i = rng.randrange(N); buf += rows[i][1]; exp.append(i)
            buf += rng.choice(others)
        elif kind == 3:
            buf += garbage() + bad(rows[rng.randrange(N)][1])
        elif kind == 4:
            buf += bad(rows[rng.randrange(N)][1])
            i = rng.randrange(N); buf += rows[i][1]; exp = [i]
        elif kind == 5:
            f = rows[rng.randrange(N)][1]
            buf += f[:-rng.randint(1, 60)]
        else:
            i = rng.randrange(N); j = rng.randrange(N)
            buf += rows[i][1] + garbage() + rows[j][1]; exp = [i, j]
        chunks = [rng.randint(1, 30) for _ in range(rng.randint(1, 8))]
        streams.append((bytes(buf), exp, chunks))

def bl(b):
    return '&[' + ','.join('0x%02x' % x for x in b) + ']'

HEAD = '''// Generated by scripts/conformance/gen_ubx_nav_pvt.py from pyubx2; do not edit.
pub struct Pvt { pub bytes: &'static [u8], pub lat_deg_e7: i32, pub lon_deg_e7: i32, pub height_mm: i32, pub h_msl_mm: i32, pub vel_n_mmps: i32, pub vel_e_mmps: i32, pub vel_d_mmps: i32, pub fix_type: u8, pub num_sv: u8 }
pub struct Stream { pub bytes: &'static [u8], pub expect: &'static [usize], pub chunks: &'static [usize] }
pub static PVT_VECTORS: &[Pvt] = &['''
out = [HEAD]
ROW = 'Pvt {{ bytes: {b}, lat_deg_e7: {lat}i32, lon_deg_e7: {lon}i32, height_mm: {height}i32, h_msl_mm: {hMSL}i32, vel_n_mmps: {velN}i32, vel_e_mmps: {velE}i32, vel_d_mmps: {velD}i32, fix_type: {fixType}, num_sv: {numSV} }},'
for d, f in rows:
    out.append(ROW.format(b=bl(f), **d))
out.append('];')
out.append('pub static STREAMS: &[Stream] = &[')
for b, e, c in streams:
    out.append('Stream {{ bytes: {0}, expect: &[{1}], chunks: &[{2}] }},'.format(bl(b), ','.join(str(x) for x in e), ','.join(str(x) for x in c)))
out.append('];')
print('\n'.join(out))

cov = {}
for name, key, signed, lo, hi in [('lat_deg_e7', 'lat', 1, -2**31, 2**31 - 1), ('lon_deg_e7', 'lon', 1, -2**31, 2**31 - 1), ('height_mm', 'height', 1, -2**31, 2**31 - 1), ('h_msl_mm', 'hMSL', 1, -2**31, 2**31 - 1), ('vel_n_mmps', 'velN', 1, -2**31, 2**31 - 1), ('vel_e_mmps', 'velE', 1, -2**31, 2**31 - 1), ('vel_d_mmps', 'velD', 1, -2**31, 2**31 - 1), ('fix_type', 'fixType', 0, 0, 255), ('num_sv', 'numSV', 0, 0, 255)]:
    vs = [d[key] for d, _ in rows]
    c = {'n': len(vs), 'zero': sum(1 for v in vs if v == 0), 'max': sum(1 for v in vs if v == hi)}
    if signed:
        c['neg'] = sum(1 for v in vs if v < 0)
        c['min'] = sum(1 for v in vs if v == lo)
    cov[name] = c
cov['streams'] = {'n': len(streams)}
cov['skipped'] = skipped
cov['scales'] = {k: v for k, v in scale.items()}
sys.stderr.write(json.dumps(cov) + '\n')
