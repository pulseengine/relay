import json, math, random, struct, sys
from pymavlink.dialects.v20 import common as m

SEED = 20240611
N_RANDOM = 180
F32_MAX = (2.0 - 2.0 ** -23) * 2.0 ** 127
MIN_NORMAL = 2.0 ** -126


def f32r(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def fbits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def ok(x):
    if not math.isfinite(x):
        return False
    if x == 0.0:
        return math.copysign(1.0, x) > 0
    return abs(x) >= MIN_NORMAL


FLOAT_BOUNDS = [f32r(x) for x in (0.0, 1.0, -1.0, 0.5, -0.5, 12.34, -56.78, 473977000.0, 16777216.0, -16777216.0, 1e10, 1e30, -1e30, F32_MAX, -F32_MAX, MIN_NORMAL, -MIN_NORMAL)]
assert all(ok(x) for x in FLOAT_BOUNDS)
CMDS = sorted({0, 1, 2, 3, 7, 15, 20, 21, 22, 185, 255, 256, 300, 400, 4095, 32767, 32768, 65534, 65535, 0xAABB})
U8B = [0, 1, 2, 3, 7, 15, 63, 127, 128, 254, 255]

rng = random.Random(SEED)


def rand_f32():
    while True:
        mode = rng.randrange(5)
        try:
            if mode == 0:
                x = struct.unpack('<f', struct.pack('<I', rng.getrandbits(32)))[0]
            elif mode == 1:
                x = f32r(rng.uniform(-1000.0, 1000.0))
            elif mode == 2:
                x = f32r(rng.choice((-1.0, 1.0)) * rng.random() * 10.0 ** rng.uniform(0, 38))
            elif mode == 3:
                x = f32r(float(rng.randint(-2 ** 31, 2 ** 31 - 1)))
            else:
                x = 0.0
        except OverflowError:
            continue
        if ok(x):
            return x


mav = m.MAVLink(None, srcSystem=1, srcComponent=1)


def vec(p=None, cmd=76, ts=1, tc=1, conf=0):
    return {'p': list(p) if p else [0.0] * 7, 'cmd': cmd, 'ts': ts, 'tc': tc, 'conf': conf}


def build(v):
    kw = {'param%d' % (i + 1): v['p'][i] for i in range(7)}
    msg = m.MAVLink_command_long_message(target_system=v['ts'], target_component=v['tc'], command=v['cmd'], confirmation=v['conf'], **kw)
    mav.seq = 0
    packed = bytes(msg.pack(mav))
    size = msg.unpacker.size
    payload = packed[10:-2]
    if packed[0] != 0xFD or packed[1] != len(payload) or len(payload) > size:
        raise ValueError('frame')
    payload = payload + bytes(size - len(payload))
    if size != 33:
        raise ValueError('size')
    for i in range(7):
        if fbits(getattr(msg, 'param%d' % (i + 1))) != fbits(v['p'][i]):
            raise ValueError('param')
    if msg.command != v['cmd'] or msg.target_system != v['ts'] or msg.target_component != v['tc'] or msg.confirmation != v['conf']:
        raise ValueError('int field')
    return payload, msg


probe = build(vec())[1]
REF_ID = probe.id
REF_CRC = probe.crc_extra
REF_LEN = probe.unpacker.size

cands = []
for i in range(7):
    for b in FLOAT_BOUNDS:
        p = [0.0] * 7
        p[i] = b
        cands.append(vec(p, cmd=400))
for b in FLOAT_BOUNDS:
    cands.append(vec([b] * 7, cmd=22))
for c in CMDS:
    cands.append(vec([rand_f32() for _ in range(7)], cmd=c))
for x in U8B:
    cands.append(vec(cmd=400, ts=x))
    cands.append(vec(cmd=400, tc=x))
    cands.append(vec(cmd=400, conf=x))
for _ in range(N_RANDOM):
    cmd = rng.choice(CMDS) if rng.random() < 0.4 else rng.getrandbits(16)
    ts = rng.choice(U8B) if rng.random() < 0.2 else rng.getrandbits(8)
    tc = rng.choice(U8B) if rng.random() < 0.2 else rng.getrandbits(8)
    cf = rng.choice(U8B) if rng.random() < 0.2 else rng.getrandbits(8)
    cands.append(vec([rand_f32() for _ in range(7)], cmd=cmd, ts=ts, tc=tc, conf=cf))

good = []
skipped = 0
for v in cands:
    try:
        payload, _msg = build(v)
        good.append((v, payload))
    except Exception:
        skipped += 1

FLOATS = ['param%d' % i for i in range(1, 8)]
INTS = [('command', 65535), ('target_system', 255), ('target_component', 255), ('confirmation', 255)]
cov = {}
for f in FLOATS:
    cov[f] = {'n': 0, 'neg': 0, 'zero': 0, 'min': 0, 'max': 0}
for f, _mx in INTS:
    cov[f] = {'n': 0, 'zero': 0, 'max': 0}

HEADER = """// @generated by scripts/conformance/gen_mavlink_command_long.py (SEED={seed}); do not edit.
#[derive(Clone, Copy, Debug)]
pub struct CmdVec {{
    pub payload: [u8; 33],
    pub param_bits: [u32; 7],
    pub command: u16,
    pub target_system: u8,
    pub target_component: u8,
    pub confirmation: u8,
}}
#[derive(Clone, Copy, Debug)]
pub struct NegVec {{
    pub bytes: &'static [u8],
}}
pub const REF_MSG_ID: u32 = {mid};
pub const REF_CRC_EXTRA: u8 = {crc};
pub const REF_PAYLOAD_LEN: usize = {plen};
pub static COMMAND_LONG_VECTORS: &[CmdVec] = &["""

ROW = "    CmdVec {{ payload: [{hb}], param_bits: [{pb}], command: {c}, target_system: {ts}, target_component: {tc}, confirmation: {cf} }},"

out = []
w = out.append
w(HEADER.format(seed=SEED, mid=REF_ID, crc=REF_CRC, plen=REF_LEN))
KEYS = {'command': 'cmd', 'target_system': 'ts', 'target_component': 'tc', 'confirmation': 'conf'}
for v, payload in good:
    pb = ', '.join('0x%08x' % fbits(x) for x in v['p'])
    hb = ', '.join('0x%02x' % b for b in payload)
    w(ROW.format(hb=hb, pb=pb, c=v['cmd'], ts=v['ts'], tc=v['tc'], cf=v['conf']))
    for i, f in enumerate(FLOATS):
        x = v['p'][i]
        c = cov[f]
        c['n'] += 1
        if x < 0:
            c['neg'] += 1
        if x == 0.0:
            c['zero'] += 1
        if x == -F32_MAX:
            c['min'] += 1
        if x == F32_MAX:
            c['max'] += 1
    for f, mx in INTS:
        val = v[KEYS[f]]
        c = cov[f]
        c['n'] += 1
        if val == 0:
            c['zero'] += 1
        if val == mx:
            c['max'] += 1
w('];')

neg = []
for v, payload in good[:3]:
    for ln in (0, 1, 4, 28, 32, 34, 35, 64):
        if ln < 33:
            neg.append(payload[:ln])
        else:
            neg.append(payload + bytes(rng.getrandbits(8) for _ in range(ln - 33)))
w('pub static COMMAND_LONG_NEG: &[NegVec] = &[')
for b in neg:
    w('    NegVec {{ bytes: &[{0}] }},'.format(', '.join('0x%02x' % x for x in b)))
w('];')

print('\n'.join(out))
cov['skipped'] = skipped
sys.stderr.write(json.dumps(cov, sort_keys=True) + '\n')
